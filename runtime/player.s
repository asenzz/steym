;========================================================
; Atari STE YM2149 44 kHz-class player runtime
;
; Motorola 68000
;
; Fixed sample slot:
;     182 CPU cycles
;
; The YM sample code is generated separately by
; player_codegen.c and included below.
;
;========================================================


        section text


YM_TIMER_B_VECTOR  equ $120
MFP_BASE           equ $fffffa00

MFP_IERA           equ $fffffa07
MFP_IMRA           equ $fffffa13

MFP_TBCR           equ $fffffa1b
MFP_TBDR           equ $fffffa21



;--------------------------------------------------------
; Initialize player
;
; A0 = address of generated YM stream
;
;--------------------------------------------------------

player_init:

        move.l  a0,generated_code_ptr


        ; Disable Timer B

        move.b  #0,MFP_TBCR



        ; Load timer delay value
        ;
        ; Actual value depends on MFP clock divider.
        ;
        ; The compiler can patch this.

        move.b  #timer_reload,MFP_TBDR



        ; Enable Timer B interrupt

        bset    #0,MFP_IMRA



        ; Start Timer B

        move.b  #8,MFP_TBCR



        rts



;--------------------------------------------------------
; Timer B interrupt handler
;
; Minimal overhead.
;
; Dedicated registers:
;
; A0 = generated code pointer
;
;--------------------------------------------------------

timer_b_irq:


        move.l  generated_code_ptr,a0


        jsr     (a0)


        move.l  a0,generated_code_ptr



        rte



;--------------------------------------------------------
; Runtime variables
;--------------------------------------------------------

        section data


generated_code_ptr:

        dc.l    0



;--------------------------------------------------------
; Patch point generated by compiler
;--------------------------------------------------------

timer_reload:

        dc.b    0



;--------------------------------------------------------
; Generated YM code inclusion
;
; player_codegen.c generates this file.
;
;--------------------------------------------------------

        include "generated_player.s"
